import mongoose, { Document, Schema } from 'mongoose';

export interface IUser extends Document {
  name: string;
  email: string;
  passwordHash: string;
  role: 'user' | 'admin' | 'agency';
  plan: 'free' | 'pro' | 'agency';
  companyName?: string;
  whiteLabelSettings?: {
    logoUrl?: string;
    brandColor?: string;
    reportFooterText?: string;
  };
  createdAt: Date;
  updatedAt: Date;
}

const UserSchema = new Schema<IUser>(
  {
    name: { type: String, required: true, trim: true },
    email: { type: String, required: true, unique: true, lowercase: true, trim: true },
    passwordHash: { type: String, required: true },
    role: { type: String, enum: ['user', 'admin', 'agency'], default: 'user' },
    plan: { type: String, enum: ['free', 'pro', 'agency'], default: 'free' },
    companyName: { type: String, default: '' },
    whiteLabelSettings: {
      logoUrl: { type: String, default: '' },
      brandColor: { type: String, default: '#0066FF' },
      reportFooterText: { type: String, default: 'Generated by SiteAudit Pro' },
    },
  },
  { timestamps: true }
);

export const User = mongoose.model<IUser>('User', UserSchema);
